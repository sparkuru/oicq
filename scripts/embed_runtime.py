#!/usr/bin/env python3
"""Embed the JavaScript runtime into a generated C++ translation unit.

The native layer only needs the payload as bytes: it writes every file into
<tmp>/oicq/ at startup and prepends `require('<tmp>/oicq/boot.cjs')` to the
anchored V8 source. Keeping the runtime out of the C++ sources means the JS is
editable without touching the injection code, and diffs stay reviewable.

Inputs: runtime/*.js (boot.cjs <- main.js, minimal.cjs <- minimal.js,
protocol.js, renderer.js). Output: resources_gen.cc.
"""
from __future__ import annotations

import argparse
import pathlib

# (embedded file name, source file name)
PAYLOAD = [
    ("boot.cjs", "main.js"),
    ("minimal.cjs", "minimal.js"),
    ("protocol.js", "protocol.js"),
    ("renderer.js", "renderer.js"),
]


def emit_bytes(identifier: str, data: bytes) -> list[str]:
    lines = [f"static const unsigned char {identifier}[] = {{"]
    for index in range(0, len(data), 24):
        chunk = data[index : index + 24]
        lines.append("  " + ",".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.append("};")
    lines.append(f"static constexpr std::size_t {identifier}Size = {len(data)};")
    return lines


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime", required=True, help="directory holding the JS runtime")
    parser.add_argument("--out", required=True, help="generated .cc file")
    args = parser.parse_args()

    runtime_dir = pathlib.Path(args.runtime)
    body: list[str] = [
        "// Generated by scripts/embed_runtime.py -- do not edit.",
        '#include "oicq/resource.h"',
        "",
        "namespace oicq {",
        "namespace {",
    ]
    table: list[str] = []
    for index, (name, source_name) in enumerate(PAYLOAD):
        source = runtime_dir / source_name
        if not source.is_file():
            raise SystemExit(f"missing runtime file: {source}")
        identifier = f"kPayload{index}"
        body.extend(emit_bytes(identifier, source.read_bytes()))
        table.append(f'    {{"{name}", {identifier}, {identifier}Size}},')

    body.append("")
    body.append("constexpr std::size_t kFileCount = " + str(len(PAYLOAD)) + ";")
    body.append("const EmbeddedFile kFiles[kFileCount] = {")
    body.extend(table)
    body.append("};")
    body.append("")
    body.append("}  // namespace")
    body.append("")
    body.append("const EmbeddedFile* embedded_files() { return kFiles; }")
    body.append("std::size_t embedded_file_count() { return kFileCount; }")
    body.append("")
    body.append("}  // namespace oicq")
    body.append("")

    out_path = pathlib.Path(args.out)
    # Atomic replace: a parallel build must never compile a half-written file.
    temp_path = out_path.with_suffix(out_path.suffix + ".tmp")
    temp_path.write_text("\n".join(body), encoding="utf-8")
    temp_path.replace(out_path)
    sizes = ", ".join(f"{name}={ (runtime_dir / src).stat().st_size }" for name, src in PAYLOAD)
    print(f"embedded runtime: {sizes} -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
