#!/usr/bin/env bash
# Render qq.desktop for an oicq.so and a Linux QQ installation directory.
set -Eeuo pipefail

readonly SCRIPT_NAME=${0##*/}
readonly MARKER='# Generated by oicq install.sh'

usage() {
    cat <<EOF
Usage: $SCRIPT_NAME /path/to/oicq.so /path/to/linux-qq-dir

Write qq.desktop in the current directory. The entry starts <linux-qq-dir>/qq with LD_PRELOAD pointing at oicq.so.

Verified with QQNT Linux 3.2.18-37012 and 3.2.35-54395. Other versions are untested; check the anchors before relying on them.
EOF
}

die() {
    printf 'error: %s\n' "$*" >&2
    exit 1
}

main() {
    local so qq_dir qq_bin desktop

    if [[ $# -eq 1 && ($1 == --help || $1 == -h) ]]; then
        usage
        return 0
    fi
    [[ $# -eq 2 ]] || {
        usage >&2
        return 1
    }

    so=$1
    qq_dir=$2

    [[ -f $so ]] || die "no such library: $so"
    [[ -d $qq_dir ]] || die "no such QQ directory: $qq_dir"

    so=$(readlink -f -- "$so")
    qq_dir=$(readlink -f -- "$qq_dir")
    qq_bin=$qq_dir/qq
    [[ -x $qq_bin ]] || die "no executable qq in $qq_dir"

    desktop=$PWD/qq.desktop
    if [[ -e $desktop ]] && ! grep -qxF -- "$MARKER" "$desktop"; then
        die "refusing to overwrite $desktop (not generated by this script)"
    fi

    cat >"$desktop" <<EOF
$MARKER
[Desktop Entry]
Type=Application
Name=QQ
Name[zh_CN]=linuxqq
GenericName=QQ
Comment=QQ (oicq injected)
Comment[zh_CN]=linuxqq
TryExec=$qq_bin
Exec=env LD_PRELOAD=$so OICQ_SHIELD=1 $qq_bin %U
Icon=$qq_bin
Terminal=false
Categories=Network;InstantMessaging;
StartupWMClass=QQ
StartupNotify=true
EOF
    chmod 0644 -- "$desktop"

    printf 'file: qq.desktop\n'
    printf "recommend: \`cp \$PWD/qq.desktop \$HOME/.local/share/applications\`\n"
}

main "$@"
